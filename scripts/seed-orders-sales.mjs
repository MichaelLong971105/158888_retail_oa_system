const BASE_URL = process.env.SEED_BASE_URL || 'http://127.0.0.1:8080'
const USERNAME = process.env.SEED_USERNAME || 'admin'
const PASSWORD = process.env.SEED_PASSWORD || 'Admin@123456'
const ORDER_COUNT = Number(process.env.SEED_ORDER_COUNT || 24)
const SALES_COUNT = Number(process.env.SEED_SALES_COUNT || 48)
const SUPPLIER_TARGET = Number(process.env.SEED_SUPPLIER_TARGET || 4)
const PRODUCT_TARGET = Number(process.env.SEED_PRODUCT_TARGET || 10)
const RUN_TAG = new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14)

// Small cookie-aware client so the seed script can exercise the real session-based API.
class ApiClient {
  constructor(baseUrl) {
    this.baseUrl = baseUrl
    this.cookie = ''
  }

  async request(path, options = {}) {
    const headers = {
      'Content-Type': 'application/json',
      ...(options.headers || {})
    }

    if (this.cookie) {
      headers.Cookie = this.cookie
    }

    const response = await fetch(`${this.baseUrl}${path}`, {
      ...options,
      headers
    })

    const setCookie = response.headers.get('set-cookie')
    if (setCookie) {
      this.cookie = setCookie.split(',').map(part => part.split(';')[0]).join('; ')
    }

    if (response.status === 204) {
      return null
    }

    const text = await response.text()
    const data = text ? JSON.parse(text) : null

    if (!response.ok) {
      throw new Error(`${response.status} ${response.statusText}: ${data?.error || data?.message || text}`)
    }

    return data
  }
}

const client = new ApiClient(BASE_URL)

function randomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min
}

function pickRandom(list) {
  return list[randomInt(0, list.length - 1)]
}

function pickDistinct(list, count) {
  const copy = [...list]
  const picked = []
  const safeCount = Math.min(count, list.length)

  while (picked.length < safeCount) {
    const index = randomInt(0, copy.length - 1)
    picked.push(copy[index])
    copy.splice(index, 1)
  }

  return picked
}

function randomPhone(index) {
  return `1380000${String(index).padStart(4, '0')}`
}

function randomSaleTime(index) {
  const now = new Date()
  const dayOffset = index < Math.ceil(SALES_COUNT / 2) ? 0 : randomInt(1, 6)
  const saleTime = new Date(now.getTime() - dayOffset * 24 * 60 * 60 * 1000)
  saleTime.setHours(randomInt(9, 21), randomInt(0, 59), randomInt(0, 59), 0)
  return saleTime.toISOString().slice(0, 19)
}

async function login() {
  // Try the current bootstrap account first, then fall back to an older local demo account.
  const candidates = [
    { username: USERNAME, password: PASSWORD },
    { username: 'admin1', password: '123456' }
  ]
  const tried = new Set()
  let lastError = null

  for (const candidate of candidates) {
    const key = `${candidate.username}:${candidate.password}`
    if (tried.has(key)) {
      continue
    }
    tried.add(key)

    try {
      const response = await client.request('/auth/login', {
        method: 'POST',
        body: JSON.stringify(candidate)
      })

      if (!response?.user?.id) {
        throw new Error('Login succeeded but no user payload was returned')
      }

      return response.user
    } catch (error) {
      lastError = error
    }
  }

  throw lastError || new Error('Login failed')
}

async function getSuppliers() {
  return client.request('/suppliers', { method: 'GET' })
}

async function getProducts() {
  return client.request('/products', { method: 'GET' })
}

async function ensureSuppliers() {
  const suppliers = []

  for (let i = 0; i < SUPPLIER_TARGET; i++) {
    const supplier = await client.request('/suppliers', {
      method: 'POST',
      body: JSON.stringify({
        name: `Seed Supplier ${RUN_TAG}-${i + 1}`,
        contactPerson: `Contact ${i + 1}`,
        phone: randomPhone(i + 1),
        email: `seed-supplier-${RUN_TAG}-${i + 1}@retail.local`,
        address: `Seed Address ${i + 1}`,
        remark: `Generated by seed-orders-sales.mjs ${RUN_TAG}`
      })
    })
    suppliers.push(supplier)
  }

  return suppliers
}

function buildProductPayload(index, supplier) {
  return {
    name: `Seed Product ${RUN_TAG}-${index + 1}`,
    sku: `SEED-SKU-${RUN_TAG}-${String(index + 1).padStart(2, '0')}`,
    barcode: `690${RUN_TAG}${String(index + 1).padStart(2, '0')}`,
    category: index % 2 === 0 ? 'Beverage' : 'Snack',
    brand: index % 2 === 0 ? 'Seed Drinks' : 'Seed Foods',
    specification: index % 2 === 0 ? '500ml' : '250g',
    unit: 'pcs',
    price: Number((randomInt(8, 40) + Math.random()).toFixed(2)),
    stock: 500,
    minStock: 20,
    status: 'ACTIVE',
    description: `Generated by seed-orders-sales.mjs ${RUN_TAG}`,
    supplierIds: [supplier.id]
  }
}

async function ensureProducts(suppliers) {
  const products = []

  for (let i = 0; i < PRODUCT_TARGET; i++) {
    const supplier = suppliers[i % suppliers.length]
    const product = await client.request('/products', {
      method: 'POST',
      body: JSON.stringify(buildProductPayload(i, supplier))
    })
    products.push(product)
  }

  return products
}

function groupProductsBySupplier(products) {
  // Prefer already linked products, while the API can now auto-link a supplier after receiving an order.
  return products.reduce((map, product) => {
    const supplierIds = product.supplierIds?.length
      ? product.supplierIds
      : (product.supplierId ? [product.supplierId] : ['unassigned'])

    for (const key of supplierIds) {
      if (!map.has(key)) {
        map.set(key, [])
      }
      map.get(key).push(product)
    }
    return map
  }, new Map())
}

async function createOrders(products, suppliers) {
  const groupedProducts = groupProductsBySupplier(products)
  const created = []

  // Most orders use linked products; fallback choices can still exercise the auto-link behavior.
  for (let i = 0; i < ORDER_COUNT; i++) {
    const supplier = pickRandom(suppliers)
    const availableProducts = groupedProducts.get(supplier.id) || products
    const selectedProducts = pickDistinct(availableProducts, randomInt(1, Math.min(3, availableProducts.length)))
    const order = await client.request('/orders', {
      method: 'POST',
      body: JSON.stringify({
        supplierId: supplier.id,
        items: selectedProducts.map(product => ({
          productId: product.id,
          quantity: randomInt(5, 30)
        }))
      })
    })

    const statusRoll = Math.random()
    let finalStatus = 'PENDING'

    // Keep a mix of terminal and pending orders so dashboard stats show meaningful values.
    if (statusRoll < 0.65) {
      finalStatus = 'RECEIVED'
    } else if (statusRoll < 0.85) {
      finalStatus = 'CANCELLED'
    }

    if (finalStatus !== 'PENDING') {
      await client.request(`/orders/${order.id}/status`, {
        method: 'PUT',
        body: JSON.stringify({ status: finalStatus })
      })
    }

    created.push({
      id: order.id,
      orderNumber: order.orderNumber,
      finalStatus
    })
  }

  return created
}

async function createSales(products, cashier) {
  const created = []

  // Sales are pushed through the API to exercise stock deduction and sales analytics together.
  for (let i = 0; i < SALES_COUNT; i++) {
    const selectedProducts = pickDistinct(products, randomInt(1, Math.min(4, products.length)))
    const sale = await client.request('/sales', {
      method: 'POST',
      body: JSON.stringify({
        cashierUserId: cashier.id,
        cashierName: cashier.username,
        saleTime: randomSaleTime(i),
        remark: `Generated by seed-orders-sales.mjs ${RUN_TAG}`,
        items: selectedProducts.map(product => ({
          productId: product.id,
          quantity: randomInt(1, 4),
          unitPrice: Number(product.price)
        }))
      })
    })

    created.push({
      id: sale.id,
      saleNumber: sale.saleNumber,
      totalAmount: sale.totalAmount
    })
  }

  return created
}

async function fetchSummary() {
  const [orders, orderStats, salesToday, salesAll] = await Promise.all([
    client.request('/orders', { method: 'GET' }),
    client.request('/orders/stats', { method: 'GET' }),
    client.request('/sales/dashboard', { method: 'GET' }),
    client.request('/sales', { method: 'GET' })
  ])

  const salesTotalAmount = salesAll.reduce((total, record) => total + Number(record.totalAmount || 0), 0)

  return {
    orderCount: orders.length,
    orderStats,
    salesCount: salesAll.length,
    salesTotalAmount: salesTotalAmount.toFixed(2),
    todaySalesAmount: Number(salesToday.todaySalesAmount || 0).toFixed(2),
    todaySalesCount: salesToday.todaySalesCount || 0,
    topProducts: salesToday.topSellingProducts || []
  }
}

async function main() {
  console.log(`Seeding orders and sales through API at ${BASE_URL}`)
  const cashier = await login()
  console.log(`Logged in as ${cashier.username} (${cashier.role})`)

  const suppliers = await ensureSuppliers()
  console.log(`Suppliers ready: ${suppliers.length}`)

  const products = await ensureProducts(suppliers)
  if (products.length < 2) {
    throw new Error('At least two active products are required to seed orders and sales')
  }
  console.log(`Active products ready: ${products.length}`)

  const orders = await createOrders(products, suppliers)
  console.log(`Created ${orders.length} orders`)

  const sales = await createSales(products, cashier)
  console.log(`Created ${sales.length} sales records`)

  const summary = await fetchSummary()
  console.log('')
  console.log('Seed summary')
  console.log(`Orders in system: ${summary.orderCount}`)
  console.log(`Order total amount: ${Number(summary.orderStats.totalAmount || 0).toFixed(2)}`)
  console.log(`Received order amount: ${Number(summary.orderStats.receivedAmount || 0).toFixed(2)}`)
  console.log(`Sales in system: ${summary.salesCount}`)
  console.log(`Sales total amount: ${summary.salesTotalAmount}`)
  console.log(`Today sales amount: ${summary.todaySalesAmount}`)
  console.log(`Today sales count: ${summary.todaySalesCount}`)
  console.log(`Top selling products today: ${summary.topProducts.length}`)
}

main().catch((error) => {
  console.error('Seeding failed')
  console.error(error.message)
  process.exitCode = 1
})
